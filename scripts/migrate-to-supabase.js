import { createClient } from '@supabase/supabase-js'
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

// Load environment variables directly since this runs outside Vite
import dotenv from 'dotenv'
dotenv.config({ path: path.resolve(__dirname, '../.env.local') })

const supabaseUrl = process.env.VITE_SUPABASE_URL
const supabaseServiceKey = process.env.SUPABASE_SERVICE_ROLE_KEY // Needed to bypass RLS for migration

if (!supabaseUrl || !supabaseServiceKey) {
  console.error("Missing SUPABASE_SERVICE_ROLE_KEY or VITE_SUPABASE_URL in .env.local")
  process.exit(1)
}

const supabase = createClient(supabaseUrl, supabaseServiceKey)

async function migrateProjects() {
  console.log("Migrating Projects...")
  try {
    const projectsData = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../src/json files/Projects.json'), 'utf8'))
    
    // The JSON has 'image' field, we will map it to 'image_url' to match our new schema
    const projectsToInsert = projectsData.map(p => ({
      title: p.title,
      category: p.category,
      description: p.description,
      image_url: p.image, // Map 'image' to 'image_url'
      status: p.status,
      impact: p.impact
      // id will be auto-generated by Supabase
    }))

    const { error } = await supabase.from('projects').insert(projectsToInsert)
    if (error) throw error

    console.log(`Successfully migrated ${projectsToInsert.length} projects!`)
  } catch (err) {
    console.error("Error migrating projects:", err)
  }
}

async function migrateGallery() {
  console.log("Migrating Gallery...")
  try {
    let rawData = fs.readFileSync(path.resolve(__dirname, '../src/data/gallery.json'), 'utf8')
    if (rawData.charCodeAt(0) === 0xFEFF) {
      rawData = rawData.slice(1);
    }
    const galleryData = JSON.parse(rawData)
    
    // The gallery JSON is an array of strings (image paths)
    const galleryToInsert = galleryData.map(imagePath => ({
      image_url: imagePath
      // id will be auto-generated by Supabase
    }))

    const { error } = await supabase.from('gallery').insert(galleryToInsert)
    if (error) throw error

    console.log(`Successfully migrated ${galleryToInsert.length} gallery images!`)
  } catch (err) {
    console.error("Error migrating gallery:", err)
  }
}

async function main() {
  console.log("Starting Migration...")
  // await migrateProjects()
  await migrateGallery()
  console.log("Migration Complete!")
}

main()
